"""Central configuration. Values come from OCEANEYE_* environment variables / .env.

No secrets live in source. ``secret_key`` and the Web Push private key have no defaults and are
required in production. Parameters marked PROPOSED SCAFFOLD / experimental are placeholders, not
project requirements.

Several worker settings accept an "auto" placeholder (``auto`` for names, ``0`` for numbers). Auto
means *decide from this machine* - see :mod:`app.vision.profiles` and
:func:`app.shared.hardware.recommend_worker_slots`. Anything set explicitly always wins: fixing a
value in ``.env`` overrides the policy for that field only.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Annotated, Literal

from pydantic import SecretStr, field_validator, model_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

from app.shared.hardware import recommend_worker_slots

AUTO = "auto"


def _split_csv(value):
    if isinstance(value, str):
        return [item.strip() for item in value.split(",") if item.strip()]
    return value


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="OCEANEYE_", env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )

    # application
    environment: Literal["development", "test", "production"] = "development"
    app_name: str = "OceanEye"
    app_version: str = "0.3.0"
    host: str = "127.0.0.1"
    port: int = 8000

    # api / cors
    api_prefix: str = "/api"
    cors_origins: Annotated[list[str], NoDecode] = []

    # TLS. Needed for installable PWAs and background Web Push on phones: browsers only expose
    # service workers, the Notification API and the Push API on a secure origin (https, or localhost).
    # scripts/make_certs.py writes a self-signed pair covering localhost and this PC's LAN address.
    ssl_certfile: Path | None = None
    ssl_keyfile: Path | None = None

    # logging
    log_level: str = "INFO"
    log_json: bool = False

    # persistence / storage
    database_url: str = "sqlite:///./data/oceaneye.db"
    evidence_dir: Path = Path("./data/evidence")

    # security
    auth_mode: Literal["dev", "token"] = "dev"
    secret_key: SecretStr | None = None
    allowed_stream_schemes: Annotated[list[str], NoDecode] = ["rtsp", "rtsps", "http", "https", "mock"]

    # notifications / alerting (PROPOSED SCAFFOLD placeholders)
    notification_channels: Annotated[list[str], NoDecode] = ["websocket", "mock"]
    ack_timeout_seconds: int = 30  # reference sample payload shows a 30 s deadline; experimental
    escalation_monitor_enabled: bool = True
    escalation_check_interval_seconds: float = 5.0

    # Web Push (background phone alerts). Keys are generated by scripts/make_push_keys.py and kept
    # out of source control. Without them the web_push channel refuses to start.
    vapid_public_key: str | None = None
    vapid_private_key: SecretStr | None = None
    vapid_subject: str = "mailto:oceaneye@example.invalid"  # contact for the push service, per RFC 8292
    push_ttl_seconds: int = 120  # a drowning alert is worthless if delivered late

    # external environmental data (Open-Meteo: free, no API key - reference PDF section 8)
    weather_provider: Literal["mock", "open_meteo"] = "open_meteo"
    open_meteo_forecast_url: str = "https://api.open-meteo.com/v1/forecast"
    open_meteo_marine_url: str = "https://marine-api.open-meteo.com/v1/marine"
    external_cache_ttl_seconds: int = 600
    external_timeout_seconds: float = 12.0

    # Place search and map tiles, both from one Geoapify key (https://myprojects.geoapify.com).
    # One key replaces the OpenStreetMap Overpass lookup, which rate-limited constantly, and the
    # OSM tile servers, which refuse direct use by applications.
    #
    # The key is a SECRET and is never sent to the browser: place search runs server-side, and map
    # tiles are proxied through /api/map/tiles/... (see app.environment.api.tiles). A key pasted
    # into a web page is a key anyone who opens that page can take.
    places_provider: Literal["mock", "geoapify"] = "geoapify"
    geoapify_api_key: SecretStr | None = None
    map_style: str = "osm-bright-smooth"  # any Geoapify raster style
    map_tile_cache_entries: int = 2000    # tiles held in memory; each is a few KB
    map_max_zoom: int = 19
    # Satellite needs no key, so it stays a direct URL. Useful for placing a camera on a shoreline.
    map_satellite_url: str = ("https://server.arcgisonline.com/ArcGIS/rest/services/"
                              "World_Imagery/MapServer/tile/{z}/{y}/{x}")
    map_satellite_attribution: str = "Imagery &copy; Esri"

    # Deployment site. In the field OceanEye runs for ONE beach, operated by that beach's authority;
    # these values seed that beach the first time the system starts. The region/beach picker in the
    # Control Room exists so the prototype can be demonstrated for any coastline.
    default_region: str = "Karnataka, India"
    default_location_name: str = "Tannirbhavi Beach, Mangaluru"
    default_lat: float = 12.8406
    default_lon: float = 74.8016
    beach_authority_name: str = "Beach authority (configure in .env)"
    beach_authority_phone: str | None = None
    emergency_phone: str = "112"  # India's single emergency number; shown to lifeguards

    # video processing (uploads, analysis jobs, live camera workers) - PROPOSED SCAFFOLD
    upload_dir: Path = Path("./data/uploads")
    jobs_dir: Path = Path("./data/jobs")
    logs_dir: Path = Path("./data/logs")
    max_upload_mb: int = 500
    max_workers: int = 0  # 0 = auto (sized from GPU/CPU memory); each worker loads its own model
    #: Where a worker subprocess calls the API back. Left unset it is DERIVED from this server's
    #: own scheme, host and port (see ``_derive_worker_api_url``) - it must never be hardcoded.
    #: A fixed "http://127.0.0.1:8000" silently broke every worker the moment TLS was switched on:
    #: a plaintext request to a TLS socket is closed without a reply, so the worker died with
    #: "Remote end closed connection without response" and the job showed only "exited with code 1".
    #: Set it explicitly only when the worker must reach the API by some other address.
    worker_api_url: str | None = None
    worker_model: str = AUTO  # auto | yolov8n.pt | yolov8s.pt | ... | a path to .pt weights
    worker_imgsz: int = 0  # 0 = auto
    worker_device: str = AUTO  # auto | cpu | cuda:0 | mps
    worker_target_fps: float = 0.0  # 0 = auto; frames analysed per second per camera
    worker_threads: int = 2  # CPU threads per worker (prevents freezing the PC)
    worker_sensitivity: Literal["low", "medium", "high"] = "medium"
    worker_clip_max_width: int = 0  # 0 = auto; evidence-clip frames are stored at this width

    # risk engine experimental parameters: intentionally unset (decide via experiments)
    risk_persistence_window_seconds: float | None = None

    @field_validator("cors_origins", "notification_channels", "allowed_stream_schemes", mode="before")
    @classmethod
    def _csv(cls, v):
        return _split_csv(v)

    @property
    def places_enabled(self) -> bool:
        return self.places_provider == "geoapify" and self.geoapify_api_key is not None

    @property
    def map_tiles_enabled(self) -> bool:
        return self.geoapify_api_key is not None

    @model_validator(mode="after")
    def _resolve_auto_worker_count(self) -> "Settings":
        if self.max_workers <= 0:
            object.__setattr__(self, "max_workers", recommend_worker_slots())
        return self

    @model_validator(mode="after")
    def _tls_pair(self) -> "Settings":
        if bool(self.ssl_certfile) != bool(self.ssl_keyfile):
            raise ValueError("OCEANEYE_SSL_CERTFILE and OCEANEYE_SSL_KEYFILE must be set together")
        return self

    @model_validator(mode="after")
    def _push_keys_present_when_enabled(self) -> "Settings":
        if "web_push" in self.notification_channels and not (self.vapid_public_key and self.vapid_private_key):
            raise ValueError(
                "notification channel 'web_push' needs OCEANEYE_VAPID_PUBLIC_KEY and "
                "OCEANEYE_VAPID_PRIVATE_KEY - generate them with: python scripts/make_push_keys.py"
            )
        return self

    @model_validator(mode="after")
    def _production_rules(self) -> "Settings":
        if self.environment == "production":
            if self.auth_mode == "dev":
                raise ValueError("auth_mode=dev is not allowed in production")
            if self.secret_key is None:
                raise ValueError("OCEANEYE_SECRET_KEY is required in production")
            if "*" in self.cors_origins:
                raise ValueError("wildcard CORS origin is not allowed in production")
            if not self.ssl_certfile:
                raise ValueError("TLS is required in production: set OCEANEYE_SSL_CERTFILE / _KEYFILE "
                                 "(or terminate TLS in front of the app)")
        return self

    @model_validator(mode="after")
    def _derive_worker_api_url(self) -> "Settings":
        """Point workers at this server, over the scheme it actually serves.

        ``host`` may be 0.0.0.0 (``run_api.py --lan``), which is a bind address, not somewhere a
        client can connect to; a worker on this machine uses the loopback address instead. The
        loopback literal is also what the self-signed certificate carries as a SAN, so TLS
        verification succeeds without disabling it.
        """
        if self.worker_api_url is None:
            scheme = "https" if self.tls_enabled else "http"
            host = "127.0.0.1" if self.host in ("0.0.0.0", "::", "") else self.host
            object.__setattr__(self, "worker_api_url", f"{scheme}://{host}:{self.port}")
        return self

    @property
    def tls_enabled(self) -> bool:
        return bool(self.ssl_certfile and self.ssl_keyfile)

    @property
    def push_enabled(self) -> bool:
        return "web_push" in self.notification_channels


@lru_cache
def get_settings() -> Settings:
    return Settings()
