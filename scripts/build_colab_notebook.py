def bundle_b64() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted((ROOT / "app").rglob("*.py")):
            if not (set(p.relative_to(ROOT).parts) & SKIP_PARTS):
                z.write(p, p.relative_to(ROOT).as_posix())
        z.write(ROOT / "pyproject.toml", "pyproject.toml")
    return base64.b64encode(buf.getvalue()).decode("ascii")


def _src(text: str) -> list[str]:
    lines = text.strip("\n").split("\n")
    return [line + "\n" for line in lines[:-1]] + [lines[-1]]


def md(text: str) -> dict:
    return {"cell_type": "markdown", "id": uuid.uuid4().hex[:8], "metadata": {}, "source": _src(text)}


def code(text: str) -> dict:
    return {"cell_type": "code", "id": uuid.uuid4().hex[:8], "metadata": {}, "execution_count": None,
            "outputs": [], "source": _src(text)}


